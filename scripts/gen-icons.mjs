#!/usr/bin/env node
// Wrangler's documented way to import binary is Data modules (.bin -> ArrayBuffer, or `rules` with type Data;
// https://developers.cloudflare.com/workers/wrangler/bundling/ and
// https://developers.cloudflare.com/workers/wrangler/configuration/#bundling). Those are emitted as separate
// modules; this Worker is deployed as a single bundled module and its tests import src/worker.js directly under
// node --test, where a .png import does not resolve. So icons are inlined as base64 in a JS module, which esbuild
// bundles into the single worker module. No static-assets binding.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets', 'icons');
const files = [
  ['/favicon.ico', 'favicon.ico', 'image/x-icon'],
  ['/favicon.png', 'favicon-32.png', 'image/png'],
  ['/apple-touch-icon.png', 'apple-touch-icon.png', 'image/png'],
  ['/icon-512.png', 'icon-512.png', 'image/png'],
];

const entries = files.map(([path, file, type]) => {
  const b64 = readFileSync(join(dir, file)).toString('base64');
  return `  ${JSON.stringify(path)}: { type: ${JSON.stringify(type)}, b64: ${JSON.stringify(b64)} }`;
});

writeFileSync(join(root, 'src', 'icons.js'), `// Generated by scripts/gen-icons.mjs; do not edit.
export const ICONS = {
${entries.join(',\n')},
};
`);
